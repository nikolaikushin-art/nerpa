// ===================== PROGRAMMATIC GENERATOR =====================

function generateVisuals(cat: CategoryDef, multiplier: number): VisualAsset[] {
  const visuals: VisualAsset[] = [];
  const photoCount = photoPool.length;
  const titleCount = cat.titles.length;
  
  for (let i = 0; i < titleCount * multiplier; i++) {
    const titleIdx = i % titleCount;
    const photoIdx = (i * 7 + cat.key.charCodeAt(0)) % photoCount;
    const variant = Math.floor(i / titleCount);
    
    const suffixes = ['', ' — Phase II', ' — Extended View', ' — Detail Shot', ' — Panoramic',
      ' — Close-Up', ' — Operations View', ' — Engineering Detail', ' — Field Documentation',
      ' — Drone Perspective', ' — Night Operations', ' — Morning Survey', ' — Technical Review',
      ' — Progress Update', ' — Milestone Documentation', ' — Strategic Overview',
      ' — Implementation Phase', ' — Capacity Expansion', ' — Quality Assessment', ' — Performance Review',
      ' — Infrastructure Update', ' — Development Stage', ' — Commissioning Phase', ' — Operational Mode',
      ' — Full Production'];
    
    const suffix = variant === 0 ? '' : (suffixes[variant % suffixes.length] || ` — Series ${variant}`);
    
    visuals.push({
      src: `https://images.unsplash.com/photo-${photoPool[photoIdx]}?w=800&q=80`,
      alt: cat.alts[titleIdx % cat.alts.length],
      title: `${cat.titles[titleIdx]}${suffix}`,
      description: cat.descs[titleIdx % cat.descs.length],
      category: cat.key,
    });
  }
  
  return visuals;
}

