export function translateTimelineContent(
  data: TimelineData,
  language: Language,
  path: string
): TimelineData {
  if (language === 'en') {
    return data;
  }
  const key = path.toLowerCase().trim().replace(/\s+/g, '-');
  const base = timelineTranslationMaps[key];
  const gen = generatedTimelineTranslations?.[key];
  const translations = base || gen ? Object.fromEntries(
    [...new Set([...(Object.keys(base || {})), ...(Object.keys(gen || {}))])].map((lang) => [
      lang,
      { ...(base?.[lang] || {}), ...(gen?.[lang] || {}) },
    ])
  ) : null;
  if (!translations || !translations[language]) {
    return data;
  }

  const translated = { ...data };
  const lang = translations[language];
  // Use ONLY manual timelineTranslationMaps for sections/stats/milestones/facts/features —
  // never apply generatedTimelineTranslations to those, so generic "Historical Context & Mining Heritage"
  // boilerplate is never applied across different timeline pages.
  const langBlocks = base?.[language];
  const timelinePathsFromRegistry = (contentRegistry as { timelinePaths?: string[] }).timelinePaths ?? [];
  const useTranslatedBlocks = timelinePathsFromRegistry.includes(key) && langBlocks;

  if (langBlocks?.title) translated.title = langBlocks.title;
  if (langBlocks?.subtitle) translated.subtitle = langBlocks.subtitle;
  if (langBlocks?.overview) translated.overview = langBlocks.overview;

  if (useTranslatedBlocks && langBlocks.sections && translated.sections) {
    translated.sections = translated.sections.map((section, i) => {
      const tSection = langBlocks.sections?.[i];
      if (!tSection) return section;
      return {
        ...section,
        title: tSection.title ?? section.title,
        content: tSection.content ?? section.content,
      };
    });
  }

  if (useTranslatedBlocks && langBlocks.stats && translated.stats) {
    translated.stats = translated.stats.map((stat, i) => {
      const tStat = langBlocks.stats?.[i];
      if (!tStat) return stat;
      return {
        ...stat,
        value: tStat.value ?? stat.value,
        label: tStat.label ?? stat.label,
        description: tStat.description ?? stat.description,
      };
    });
  }

  if (useTranslatedBlocks && langBlocks.detailedTimeline && translated.detailedTimeline) {
    translated.detailedTimeline = translated.detailedTimeline.map((item, i) => {
      const tItem = langBlocks.detailedTimeline?.[i];
      if (!tItem) return item;
      return {
        year: tItem.year ?? item.year,
        event: tItem.event ?? item.event,
        details: tItem.details ?? item.details,
      };
    });
  }

  if (useTranslatedBlocks && langBlocks.milestones && translated.milestones) {
    translated.milestones = translated.milestones.map((m, i) => {
      const tM = langBlocks.milestones?.[i];
      if (!tM) return m;
      return {
        ...m,
        year: tM.year ?? m.year,
        title: tM.title ?? m.title,
        description: tM.description ?? m.description,
        impact: tM.impact ?? m.impact,
      };
    });
  }

  if (useTranslatedBlocks && langBlocks.facts && translated.facts) {
    translated.facts = translated.facts.map((f, i) => {
      const tF = langBlocks.facts?.[i];
      if (!tF) return f;
      return {
        title: tF.title ?? f.title,
        items: tF.items ?? f.items,
      };
    });
  }

  if (useTranslatedBlocks && lang.features && translated.features) {
    translated.features = translated.features.map((f, i) => {
      const tF = lang.features?.[i];
      if (!tF) return f;
      return {
        title: tF.title ?? f.title,
        items: tF.items ?? f.items,
      };
    });
  }

  if (lang.factors && translated.factors) {
    translated.factors = translated.factors.map((f, i) => {
      const tF = lang.factors?.[i];
      if (!tF) return f;
      return {
        title: tF.title ?? f.title,
        items: tF.items ?? f.items,
      };
    });
  }

  if (lang.functions && translated.functions) {
    translated.functions = translated.functions.map((f, i) => {
      const tF = lang.functions?.[i];
      if (!tF) return f;
      return {
        title: tF.title ?? f.title,
        items: tF.items ?? f.items,
      };
    });
  }

  if (lang.charts && translated.charts) {
    translated.charts = translated.charts.map((chart, i) => {
      const tChart = lang.charts?.[i];
      if (!tChart) return chart;
      return {
        ...chart,
        title: tChart.title ?? chart.title,
        description: tChart.description ?? chart.description,
        data: tChart.data ?? chart.data,
      };
    });
  }

  if (lang.tables && translated.tables) {
    translated.tables = translated.tables.map((table, i) => {
      const tTable = lang.tables?.[i];
      if (!tTable) return table;
      return {
        ...table,
        title: tTable.title ?? table.title,
        headers: tTable.headers ?? table.headers,
        rows: tTable.rows ?? table.rows,
      };
    });
  }

  return translated;
}
