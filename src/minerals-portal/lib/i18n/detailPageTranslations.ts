function normalizePath(path: string): string {
  return path.toLowerCase().trim().replace(/\s+/g, '-');
}

export function translateInvestmentContent(data: InvestmentData, language: Language, path: string): InvestmentData {
  if (language === 'en') return data;
  const key = normalizePath(path);
  const invBase = investmentByPath[key]?.[language as NonEn];
  const invGen = generatedInvestmentByPath[key]?.[language as NonEn];
  const byLang = invBase || invGen ? { ...(invGen || {}), ...(invBase || {}) } : undefined;
  if (!byLang) return data;
  const translated = { ...data };
  if (byLang.title) translated.title = byLang.title;
  if (byLang.subtitle) translated.subtitle = byLang.subtitle;
  if (byLang.overview) translated.overview = byLang.overview;
  if (byLang.stats && translated.stats) {
    translated.stats = translated.stats.map((s, i) => (byLang.stats?.[i] ? { ...s, ...byLang.stats![i] } : s));
  }
  if (byLang.sections && translated.sections) {
    translated.sections = translated.sections.map((s, i) => {
      const t = byLang.sections?.[i];
      return t ? { ...s, title: t.title ?? s.title, content: t.content ?? s.content } : s;
    });
  }
  if (byLang.processSteps && translated.processSteps) {
    translated.processSteps = translated.processSteps.map((s, i) => {
      const t = byLang.processSteps?.[i];
      return t ? { ...s, title: t.title ?? s.title, description: t.description ?? s.description } : s;
    });
  }
  if (byLang.benefits && translated.benefits) {
    translated.benefits = translated.benefits.map((s, i) => {
      const t = byLang.benefits?.[i];
      return t ? { ...s, title: t.title ?? s.title, description: t.description ?? s.description } : s;
    });
  }
  return translated;
}

