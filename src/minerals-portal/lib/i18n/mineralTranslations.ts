// Translation function for mineral content
export const translateMineralContent = (
  data: MineralData,
  language: Language,
  path: string
): MineralData => {
  if (language === 'en') {
    return data; // English is the base
  }

  const pathKey = path.toLowerCase().trim();
  const base = mineralTranslationMaps[pathKey];
  const gen = generatedMineralTranslations?.[pathKey];
  const translations = base || gen ? Object.fromEntries(
    [...new Set([...(Object.keys(base || {})), ...(Object.keys(gen || {}))])].map((lang) => [
      lang,
      { ...(base?.[lang] || {}), ...(gen?.[lang] || {}) },
    ])
  ) : null;
  if (!translations || !translations[language]) {
    return data; // Fallback to English if translation not available
  }

  const translated = { ...data };
  const langTranslations = translations[language];

  // Translate title, subtitle, overview
  if (langTranslations.title) translated.title = langTranslations.title;
  if (langTranslations.subtitle) translated.subtitle = langTranslations.subtitle;
  if (langTranslations.overview) translated.overview = langTranslations.overview;

  // Translate sections if available
  if (langTranslations.sections && translated.sections) {
    translated.sections = translated.sections.map((section, index) => {
      const translatedSection = langTranslations.sections?.[index];
      if (translatedSection) {
        return {
          ...section,
          title: translatedSection.title || section.title,
          content: translatedSection.content || section.content,
        };
      }
      return section;
    });
  }

  // Translate stats if available
  if (langTranslations.stats && translated.stats) {
    translated.stats = translated.stats.map((stat, index) => {
      const translatedStat = langTranslations.stats?.[index];
      if (translatedStat) {
        return {
          ...stat,
          label: translatedStat.label || stat.label,
          description: translatedStat.description || stat.description,
        };
      }
      return stat;
    });
  }

  // Translate timeline if available (year and event)
  if (langTranslations.timeline && translated.timeline) {
    translated.timeline = translated.timeline.map((item, index) => {
      const translatedItem = langTranslations.timeline?.[index];
      if (translatedItem) {
        return {
          ...item,
          year: translatedItem.year ?? item.year,
          event: translatedItem.event ?? item.event,
        };
      }
      return item;
    });
  }

  // Translate detailedSections if available (from mineralDatabaseExpanded)
  const dataWithDetailed = translated as MineralData & { detailedSections?: { title: string; content: string }[] };
  if (langTranslations.detailedSections && dataWithDetailed.detailedSections) {
    dataWithDetailed.detailedSections = dataWithDetailed.detailedSections.map((ds, index) => {
      const tDs = langTranslations.detailedSections?.[index];
      if (tDs) {
        return {
          title: tDs.title ?? ds.title,
          content: tDs.content ?? ds.content,
        };
      }
      return ds;
    });
  }

  // Translate relatedMinerals if available
  if (langTranslations.relatedMinerals && translated.relatedMinerals) {
    translated.relatedMinerals = translated.relatedMinerals.map((mineral, index) => {
      const translatedMineral = langTranslations.relatedMinerals?.[index];
      if (translatedMineral) {
        return {
          ...mineral,
          name: translatedMineral.name || mineral.name,
        };
      }
      return mineral;
    });
  }

  return translated;
};
